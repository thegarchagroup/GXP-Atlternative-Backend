"""Create a ready-to-run .env for local testing (only if .env does not exist yet).

- Uses a local SQLite file (hotel_local.db) so nothing else has to be installed.
  Switch to MySQL by editing DATABASE_URL in .env (see README).
- Generates a random JWT secret and a random first-admin password, and prints the password.
"""
import os
import secrets
import string
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENV_PATH = os.path.join(ROOT, ".env")


def main() -> int:
    if os.path.exists(ENV_PATH):
        print(".env already exists - leaving it unchanged.")
        return 0
    alphabet = string.ascii_letters + string.digits
    admin_pw = "".join(secrets.choice(alphabet) for _ in range(10)) + str(secrets.randbelow(10))
    content = f"""# Generated by scripts/setup_local_env.py for LOCAL testing. Do not commit.
APP_ENV=development

# Local SQLite database (file created next to main.py). For MySQL use e.g.:
# DATABASE_URL=mysql+pymysql://hotel_app:yourpassword@localhost:3306/hotel_rooms?charset=utf8mb4
DATABASE_URL=sqlite:///./hotel_local.db

JWT_SECRET_KEY={secrets.token_urlsafe(48)}
ACCESS_TOKEN_EXPIRE_MINUTES=480

# Open the web app at http://localhost:5173 (use "localhost", not 127.0.0.1)
CORS_ORIGINS=http://localhost:5173,http://127.0.0.1:5173
COOKIE_SECURE=false
COOKIE_SAMESITE=lax

HOTEL_TIMEZONE=Asia/Kolkata
UPLOAD_DIR=./uploads
MAX_UPLOAD_MB=8

AUTO_MIGRATE=true
SEED_REFERENCE_DATA=true

# First administrator, created on first start only. You must change the password at first sign-in.
BOOTSTRAP_ADMIN_USER_ID=admin
BOOTSTRAP_ADMIN_PASSWORD={admin_pw}
BOOTSTRAP_ADMIN_NAME=Front Desk Administrator

RELEASE_DEPARTMENTS=FRONT_DESK,HOUSEKEEPING,ENGINEERING
BCRYPT_ROUNDS=12
LOGIN_MAX_ATTEMPTS=5
LOGIN_LOCKOUT_MINUTES=15
"""
    with open(ENV_PATH, "w", encoding="utf-8") as fh:
        fh.write(content)
    print("Created .env for local testing.")
    print("")
    print("  First sign-in:  Department = Front Desk / Admin")
    print("                  User ID    = admin")
    print(f"                  Password   = {admin_pw}")
    print("")
    print("  (Also stored as BOOTSTRAP_ADMIN_PASSWORD in .env. You will be asked to change it.)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
